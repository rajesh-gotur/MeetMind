"""Shared FastAPI dependencies."""

import hmac
import re
from functools import lru_cache
from typing import Annotated

from fastapi import Depends, Header, HTTPException, status

from app.bot.manager import BotManager
from app.config import Settings, get_settings
from app.pipeline.memory import PieceMemory
from app.services.notes import NotesWriter
from app.services.usage import UsageLimiter

CLIENT_ID_PATTERN = re.compile(r"^[A-Za-z0-9-]{8,64}$")


def verify_app_token(
    settings: Annotated[Settings, Depends(get_settings)],
    x_meetmind_token: Annotated[str | None, Header()] = None,
) -> None:
    """Reject calls that do not come from the MeetMind extension."""
    expected = settings.server.app_token
    if not expected:
        raise HTTPException(status.HTTP_503_SERVICE_UNAVAILABLE, "Server app_token is not configured.")
    if not x_meetmind_token or not hmac.compare_digest(x_meetmind_token, expected):
        raise HTTPException(status_code=status.HTTP_401_UNAUTHORIZED, detail="Invalid app token.")


def client_id(x_meetmind_client: Annotated[str | None, Header()] = None) -> str:
    """Anonymous per-install ID generated by the extension, used for the fair-use cap."""
    if not x_meetmind_client or not CLIENT_ID_PATTERN.match(x_meetmind_client):
        raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail="Missing or invalid client ID.")
    return x_meetmind_client


@lru_cache
def get_usage_limiter() -> UsageLimiter:
    return UsageLimiter(get_settings().daily_audio_cap_seconds)


@lru_cache
def get_piece_memory() -> PieceMemory:
    """Record-here mode: what was learned per piece, kept until the notes are written."""
    return PieceMemory()


def get_notes_writer(settings: Annotated[Settings, Depends(get_settings)]) -> NotesWriter:
    return NotesWriter(settings)


@lru_cache
def get_bot_manager() -> BotManager:
    """One bot per server (it records one meeting at a time)."""
    return BotManager(get_settings(), get_usage_limiter())
